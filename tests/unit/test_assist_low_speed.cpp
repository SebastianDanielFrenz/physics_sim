real anti_stall_of(const vehicle::VehicleDesc& d) {
    for (const auto& c : d.controllers)
        if (const auto* m = std::get_if<drivetrain::ManualTcuDesc>(&c.params)) return m->auto_clutch.anti_stall_rpm;
    return 0;
}

enum class Pattern { Constant, LiftReapply, RollBack, Gear2, AutoShift, V12Launch, V12Modulated };

const char* pattern_name(Pattern p) {
    switch (p) {
    case Pattern::Constant: return "constant";
    case Pattern::LiftReapply: return "lift_reapply";
    case Pattern::RollBack: return "roll_back";
    case Pattern::Gear2: return "gear2";
    case Pattern::AutoShift: return "auto_shift";
    case Pattern::V12Launch: return "v12_wot";
    case Pattern::V12Modulated: return "v12_0.6_to_40";
    }
    return "?";
}

struct Case {
    bool v12 = false;
    std::string surface = "grass";
    real grade = 0.08;
    real v0 = 0.4;
    real throttle = 1.0;
    int mode = 1;
    Pattern pattern = Pattern::Constant;
    real seconds = 8.0;
    int workers = 4;
    bool trace = false;
    bool stop_at_100 = false;
    bool arm_alloc = false;
    bool keep_hashes = false;
    // V12 reproduction only: racing_game test_hyper_rear_travel.cpp's start - chassis half z 0.12, settle 2 s in N
    // with the ignition off and no handbrake, then ignition + starter, throttle 1 once Running, auto-shift from N,
    // tyre rolling-resistance speed law "quadratic" (rg::SessionConfig's default).
    bool racing_rig = false;
    // V12 reproduction only: > 0 replaces the mesh ground by rg::Session's untagged static box {h, h, 0.5}, top at z 0.
    real ground_box_half = 0.0;
    real substep_window_t0 = 1e9, substep_window_t1 = -1; // racing_rig trace: per-substep wheel dump in [t0, t1]
};

struct Result {
    bool excluded = false;
    real f_req = 0, f_avail = 0, fz_rear_settled = 0;
    real v_end = 0, v_min = 1e9;
    bool stalled = false;
    real t_stall = -1;
    real rpm_min = 1e9, rpm_max = 0;
    int dumps = 0;
    real t100 = -1;                 // first time the chassis reaches 100 km/h (stop_at_100 runs)
    real fz_rear_peak_substep = 0;  // max over substeps of the rear axle's fz sum (0..100 km/h)
    real cap_ticks = 0;             // ticks with the TC clutch cap active (PowertrainDebug::tc_via_clutch)
    std::uint64_t own_alloc = 0;
    std::vector<std::uint64_t> hashes;
    std::uint64_t final_hash = 0;
};

Result run_racing_rig(const Case& c, const vehicle::VehicleDesc& desc, ps_test::VehicleTestRig& rig, const Vec3& dir) {
    World& w = *rig.world;
    const real anti_stall = anti_stall_of(desc);
    w.set_control("assist.traction_control", static_cast<real>(c.mode));
    w.set_control("ignition", 0.0);
    for (int i = 0; i < 480; ++i) w.step();
    Result r;
    r.fz_rear_settled = w.wheel_telemetry(rig.vehicle, 2).fz + w.wheel_telemetry(rig.vehicle, 3).fz;
    w.set_control("ignition", 1.0);
    w.set_control("starter", 1.0);
    w.set_control("assist.auto_shift", 1.0);
    w.set_control("assist.auto_clutch", 1.0);
    w.set_control("assist.auto_blip", 1.0);
    w.set_control("gear_request", drivetrain::kGearRequestNone);
    bool started = false;
    real prev_e = -1, fz_win = 0;
    const int n = static_cast<int>(c.seconds * 240.0 + 0.5);
    if (c.trace) std::printf("    t    kmh g   rpm st     e   tcFr  boost  fzR_max4  vz\n");
    for (int k = 0; k < n; ++k) {
        if (!started && w.powertrain_state(rig.vehicle).engine_state == drivetrain::EngineState::Running) {
            w.set_control("starter", 0.0);
            started = true;
        }
        const real v_now = dot(w.get_motion(rig.chassis).linear, dir);
        w.set_control("throttle", !started ? 0.0 : (c.pattern == Pattern::V12Modulated && v_now < 40.0 / 3.6 ? 0.6 : 1.0));
        w.step();
        const auto& pt = w.powertrain_state(rig.vehicle);
        const real v = dot(w.get_motion(rig.chassis).linear, dir);
        r.v_min = std::min(r.v_min, v);
        if (started) r.rpm_min = std::min(r.rpm_min, pt.engine_rpm);
        r.rpm_max = std::max(r.rpm_max, pt.engine_rpm);
        if (started && prev_e >= 0 && pt.clutch_engagement < prev_e - 1e-9 && pt.engine_rpm < anti_stall) ++r.dumps;
        prev_e = pt.clutch_engagement;
        if (w.powertrain_debug(rig.vehicle).tc_via_clutch) r.cap_ticks += 1;
        const std::size_t ns = w.vehicle_substep_telemetry_count(rig.vehicle);
        const real tk = (k + 1) / 240.0;
        if (c.trace && tk >= c.substep_window_t0 && tk <= c.substep_window_t1) {
            const Vec3 p = w.get_pose(rig.chassis).position;
            std::printf("  tick t %.4f chassis x %.4f y %.4f z %.4f\n", tk, p.x, p.y, p.z);
            for (std::size_t s = 0; s < ns; ++s) {
                std::printf("   sub %zu", s);
                for (std::size_t wi = 0; wi < 4; ++wi) {
                    const auto& tw = w.wheel_substep_telemetry(rig.vehicle, s, wi);
                    std::printf(" | w%zu x %.5f fz %8.0f fx %7.0f kap %+.3f", wi, tw.compression, tw.fz, tw.fx, tw.slip_ratio);
                }
                std::printf("\n");
            }
        }
        for (std::size_t s = 0; s < ns; ++s) {
            const real fz = w.wheel_substep_telemetry(rig.vehicle, s, 2).fz + w.wheel_substep_telemetry(rig.vehicle, s, 3).fz;
            fz_win = std::max(fz_win, fz);
            if (r.t100 < 0) r.fz_rear_peak_substep = std::max(r.fz_rear_peak_substep, fz);
        }
        if (started && !r.stalled && pt.engine_state == drivetrain::EngineState::Stalled) {
            r.stalled = true;
            r.t_stall = (k + 1) / 240.0;
        }
        if (c.keep_hashes) r.hashes.push_back(w.state_hash());
        if (c.trace && k % 4 == 3) {
            std::printf("%6.3f %6.2f %d %5.0f %d %5.3f %6.3f %6.3f %8.0f %6.3f\n", (k + 1) / 240.0, v * 3.6, pt.gear, pt.engine_rpm,
                        int(pt.engine_state), pt.clutch_engagement, pt.traction_torque_fraction,
                        pt.engines.empty() ? 0.0 : pt.engines[0].boost_bar, fz_win, w.get_motion(rig.chassis).linear.z);
            fz_win = 0;
        }
        if (r.t100 < 0 && v >= kV100) {
            r.t100 = (k + 1) / 240.0;
            if (c.stop_at_100) break;
        }
    }
    r.v_end = dot(w.get_motion(rig.chassis).linear, dir);
    r.final_hash = w.state_hash();
    return r;
}

Result run_case(const Case& c) {
    vehicle::VehicleDesc desc = c.v12 ? v12_desc() : hyper_desc();
    if (c.racing_rig)
        for (auto& wd : desc.wheels) vehicle::select_rolling_resistance_speed_law(wd.tyre, vehicle::RollingResistanceSpeedLaw::Quadratic);
    const real anti_stall = anti_stall_of(desc);

    ps_test::VehicleTestRig rig;
    WorldConfig cfg;
    cfg.tick_rate_hz = 240.0;
    cfg.substep_rate_hz = 960.0;
    cfg.job_workers = c.workers;
    rig.world = std::make_unique<World>(cfg);
    rig.surfaces = std::make_shared<io::SurfaceTable>(std::string(PS_SOURCE_DIR) + "/data/surfaces/surfaces.json");
    const SurfaceId sid = rig.surfaces->id_for(c.surface);
    const real theta = math::atan(-c.grade);
    const Quat tilt = Quat::from_axis_angle(Vec3::unit_y(), theta);
    BodyDesc ground;
    ground.shape = ps_test::flat_surface_mesh(c.v12 ? 1000.0 : 300.0, sid);
    ground.motion = BodyMotionType::Static;
    ground.friction = 1.0;
    ground.pose.orientation = tilt;
    if (c.ground_box_half > 0) {
        ground.shape = BoxShape{Vec3{c.ground_box_half, c.ground_box_half, 0.5}};
        ground.pose.position = Vec3{0.0, 0.0, -0.5};
    }
    rig.world->create_body(ground);
    BodyDesc chassis;
    chassis.shape = BoxShape{Vec3{2.0, 0.4, c.racing_rig ? 0.12 : 0.15}};
    chassis.motion = BodyMotionType::Dynamic;
    chassis.mass = kMass;
    chassis.friction = 0.5;
    chassis.allow_sleep = false;
    chassis.pose.orientation = tilt;
    chassis.pose.position = tilt.rotate(Vec3{0.0, 0.0, 0.5});
    rig.chassis = rig.world->create_body(chassis);
    rig.world->set_surface_table(rig.surfaces);
    rig.vehicle = rig.world->create_vehicle(desc, rig.chassis);
    World& w = *rig.world;
    const Vec3 dir = tilt.rotate(Vec3::unit_x());

    if (c.racing_rig) return run_racing_rig(c, desc, rig, dir);

    const int gear = c.pattern == Pattern::Gear2 ? 2 : 1;
    w.set_control("assist.traction_control", static_cast<real>(c.mode));
    w.set_control("assist.auto_clutch", 1.0);
    w.set_control("assist.auto_blip", 1.0);
    w.set_control("handbrake", 1.0);
    w.set_control("gear_request", static_cast<real>(gear));
    const bool auto_shift = c.pattern == Pattern::AutoShift || c.v12;
    w.set_control("assist.auto_shift", auto_shift ? 1.0 : 0.0);
    ps_test::settle(w, 1.5);

    Result r;
    r.fz_rear_settled = w.wheel_telemetry(rig.vehicle, 2).fz + w.wheel_telemetry(rig.vehicle, 3).fz;
    const real mu_peak = desc.wheels[2].tyre.pdx1 * desc.wheels[2].tyre.lambda_mux;
    const real cth = 1.0 / std::sqrt(1.0 + c.grade * c.grade), sth = c.grade * cth;
    r.f_req = kMass * kG * (sth + rig.surfaces->crr_for(sid) * cth);
    r.f_avail = mu_peak * rig.surfaces->lambda_mu_for(sid) * r.fz_rear_settled;
    if (r.f_req >= r.f_avail) {
        r.excluded = true;
        return r;
    }

    const real v0 = c.pattern == Pattern::RollBack ? -0.8 : c.v0;
    if (v0 != 0) {
        Motion mo;
        mo.linear = dir * v0;
        w.backend().set_motion(rig.chassis, mo);
        vehicle::VehicleResetOptions ro;
        ro.hubs_roll_with_chassis = true;
        ro.clutch_locked = false;
        w.reset_vehicle(rig.vehicle, ro);
    }
    w.set_control("handbrake", 0.0);
    if (auto_shift) w.set_control("gear_request", drivetrain::kGearRequestNone);
    auto throttle_at = [&](real t, real v) {
        switch (c.pattern) {
        case Pattern::LiftReapply: return (t >= 2.0 && t < 2.5) || (t >= 4.0 && t < 4.25) ? 0.0 : c.throttle;
        case Pattern::V12Modulated: return v < 40.0 / 3.6 ? 0.6 : 1.0;
        default: return c.throttle;
        }
    };
    w.set_control("throttle", throttle_at(0, v0));

    namespace da = jobs::debug_alloc;
    const bool use_alloc = c.arm_alloc && da::hook_available();
    if (use_alloc) {
        da::reset();
        da::set_armed(true);
    }
    const int n = static_cast<int>(c.seconds * 240.0 + 0.5);
    real prev_e = -1;
    if (c.trace) std::printf("    t      v    rpm st     e   tcFr capOn    fzR\n");
    for (int k = 0; k < n; ++k) {
        const real t = k / 240.0;
        const real v_now = dot(w.get_motion(rig.chassis).linear, dir);
        w.set_control("throttle", throttle_at(t, v_now));
        w.step();
        const auto& pt = w.powertrain_state(rig.vehicle);
        const auto dbg = w.powertrain_debug(rig.vehicle);
        const real v = dot(w.get_motion(rig.chassis).linear, dir);
        r.v_min = std::min(r.v_min, v);
        r.rpm_min = std::min(r.rpm_min, pt.engine_rpm);
        r.rpm_max = std::max(r.rpm_max, pt.engine_rpm);
        if (prev_e >= 0 && pt.clutch_engagement < prev_e - 1e-9 && pt.engine_rpm < anti_stall) ++r.dumps;
        prev_e = pt.clutch_engagement;
        if (dbg.tc_via_clutch) r.cap_ticks += 1;
        if (r.t100 < 0) {
            const std::size_t ns = w.vehicle_substep_telemetry_count(rig.vehicle);
            for (std::size_t s = 0; s < ns; ++s)
                r.fz_rear_peak_substep = std::max(r.fz_rear_peak_substep, w.wheel_substep_telemetry(rig.vehicle, s, 2).fz +
                                                                              w.wheel_substep_telemetry(rig.vehicle, s, 3).fz);
        }
        if (!r.stalled && pt.engine_state == drivetrain::EngineState::Stalled) {
            r.stalled = true;
            r.t_stall = (k + 1) / 240.0;
        }
        if (c.keep_hashes) r.hashes.push_back(w.state_hash());
        if (c.trace && k % 24 == 0)
            std::printf("%5.2f %6.2f %6.0f %d %5.3f %6.3f %d %7.0f\n", (k + 1) / 240.0, v, pt.engine_rpm, int(pt.engine_state),
                        pt.clutch_engagement, pt.traction_torque_fraction, int(dbg.tc_via_clutch),
                        w.wheel_telemetry(rig.vehicle, 2).fz + w.wheel_telemetry(rig.vehicle, 3).fz);
        if (r.t100 < 0 && v >= kV100) {
            r.t100 = (k + 1) / 240.0;
            if (c.stop_at_100) break;
        }
    }
    if (use_alloc) {
        da::set_armed(false);
        r.own_alloc = da::own_violation_count();
    }
    r.v_end = dot(w.get_motion(rig.chassis).linear, dir);
    r.final_hash = w.state_hash();
    return r;
}

void print_row(const char* tag, const Case& c, const Result& r) {
    if (r.excluded) {
        std::printf("%-4s %-8s %5.3f %-13s m%d EXCLUDED (grip rule) F_req %.0f N >= F_avail %.0f N (Fz_rear %.0f N)\n", tag,
                    c.surface.c_str(), c.grade, pattern_name(c.pattern), c.mode, r.f_req, r.f_avail, r.fz_rear_settled);
        return;
    }
    std::printf("%-4s %-8s %5.3f %-13s m%d thr %.2f | v_end %6.3f v_min %6.3f stall %d t %5.2f rpm_min %5.0f rpm_max %5.0f dumps %3d "
                "cap %5.0f t100 %6.2f fzR_pk %7.0f (settled %6.0f) | F_req %5.0f F_avail %5.0f\n",
                tag, c.surface.c_str(), c.grade, pattern_name(c.pattern), c.mode, c.throttle, r.v_end, r.v_min, int(r.stalled), r.t_stall,
                r.rpm_min, r.rpm_max, r.dumps, r.cap_ticks, r.t100, r.fz_rear_peak_substep, r.fz_rear_settled, r.f_req, r.f_avail);
    std::fflush(stdout);
}

const std::vector<std::string> kSurfaces = {"grass", "low_mu", "dirt", "asphalt"};

// V1/V2/V4 bands, [AS] (brief).
void check_v1(const Case& c, const Result& r) {
    if (r.excluded) return;
    INFO(c.surface << " mode " << c.mode);
    CHECK(r.v_end >= 1.5);
    CHECK_FALSE(r.stalled);
}
void check_v2(const Case& c, const Result& r) {
    if (r.excluded) return;
    INFO(c.surface << " mode " << c.mode);
    CHECK(r.v_end >= 2.5);
    CHECK(r.dumps == 0);
    CHECK(r.rpm_min >= 900.0);
    CHECK_FALSE(r.stalled);
}
void check_v4(const Case& c, const Result& r) {
    if (r.excluded) return;
    INFO(c.surface << " " << pattern_name(c.pattern) << " mode " << c.mode << " throttle " << c.throttle);
    CHECK_FALSE(r.stalled);
    if (c.mode == 1 || c.mode == 2 || c.mode == 3) {
        CHECK(r.rpm_min >= 850.0);
        CHECK(r.dumps == 0);
    }
}

std::vector<Case> v4_cases() {
    std::vector<Case> out;
    struct P { Pattern p; real thr; };
    const P patterns[] = {{Pattern::Constant, 0.3}, {Pattern::Constant, 1.0}, {Pattern::LiftReapply, 1.0},
                          {Pattern::RollBack, 1.0}, {Pattern::Gear2, 1.0},    {Pattern::AutoShift, 1.0}};
    for (const auto& s : kSurfaces)
        for (const P& p : patterns)
            for (int mode = 0; mode <= 4; ++mode) {
                Case c;
                c.surface = s;
                c.grade = 0.08;
                c.pattern = p.p;
                c.throttle = p.thr;
                c.mode = mode;
                out.push_back(c);
            }
    return out;
}


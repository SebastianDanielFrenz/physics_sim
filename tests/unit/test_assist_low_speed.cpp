// Assists plan I2 (2026-10-12): traction control at crawl speed acts through the auto-clutch, not by starving the
// locked engine (D-LS1); the auto-clutch never locks onto spinning driven wheels (D-LS2); the launch law reads the
// driver's command, not the TC-lowered request (D-LS3). Part A (tests/unit/test_assist_slope_crawl_diag.cpp) found
// the limit cycle: in 1st at idle the rim speed is 3.5 m/s, so a crawl slips the tyre, the TC cuts the locked
// engine to fraction 0, the engine is dragged below the 850 rpm anti-stall, the clutch dumps and the wound-up tyre
// springs back - repeat.
//
// Rig: car_hyper.json with the Racing assist unit grafted through VehicleLoadOptions::electronics (entry id
// "assists" - the same entry the shipped car carries since I2, so this test is independent of that data commit),
// on a TILTED flat mesh (20 m cells) tagged with one surface of data/surfaces/surfaces.json; chassis box 1500 kg
// {2, .4, .15} at 0.5 m like Part A. Settle 1.5 s with handbrake + 1st requested + auto-clutch, then (v0 != 0)
// teleport the chassis to v0 along the slope with the hubs rolling and the clutch NOT locked, release the
// handbrake and apply the throttle pattern. Modes are the assist.traction_control codes 0 Off, 1 On, 2 Relaxed,
// 3 Sport, 4 Drift.
//
// Grip rule (brief): a surface/grade pair is excluded when F_req = m g (sin th + crr cos th) >= F_avail =
// pdx1 * lambda_mux * lambda_mu * Fz_rear_settled; the numbers are printed. A "dump" is a tick on which the clutch
// engagement decreases while the engine is below anti_stall_rpm (Part A's definition).
//
// Every pass band below is [AS] (the brief's, committed before the first run). Cases >= 5 s in release are [long];
// the non-[long] subset is "I2 V2 short" and "I2 V4 short".

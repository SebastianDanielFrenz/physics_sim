double seconds_since(std::chrono::steady_clock::time_point t0) {
    return std::chrono::duration<double>(std::chrono::steady_clock::now() - t0).count();
}

struct CacheDir {
    std::filesystem::path path;
    CacheDir() {
        path = std::filesystem::temp_directory_path() /
               ("ps_test_engine_map_gen_v2_" + std::to_string(reinterpret_cast<std::uintptr_t>(this)));
        std::filesystem::remove_all(path);
        std::filesystem::create_directories(path);
    }
    ~CacheDir() {
        std::error_code ec;
        std::filesystem::remove_all(path, ec);
    }
};

std::string src(const char* rel) { return std::filesystem::path(std::string(PS_SOURCE_DIR) + "/" + rel).generic_string(); }

CycleModelDesc lumped_fixture() {
    CycleModelDesc d = ps::test::make_generic_i4_cycle_desc();
    d.grid_rpm = {1000.0, 2500.0, 4000.0, 5500.0};
    d.grid_p_im = {30000.0, 60000.0, 95000.0};
    d.friction.model = FrictionModelDesc::Model::PolynomialPistonSpeed;
    d.friction.a_pa = 66619.52;
    d.friction.b_pa = 91.085;
    d.friction.c_pa = 346.81;
    return d;
}

struct Pin {
    const char* name;
    std::uint64_t content_hash;
    std::uint64_t cache_key;
};

void check_v1(const char* name, const CycleModelDesc& d, const FuelDesc& fuel, jobs::JobSystem& pool, const Pin& pin) {
    const EngineMapsPtr m = generate_engine_maps(d, fuel, MapQuality::Preview, &pool);
    const std::uint64_t key = engine_map_cache_key(d, fuel, MapQuality::Preview);
    std::printf("A5 V7 %s: content_hash 0x%016llx, cache_key 0x%016llx, version %u\n", name,
                static_cast<unsigned long long>(m->content_hash), static_cast<unsigned long long>(key),
                static_cast<unsigned>(m->generator_version));
    CHECK(m->generator_version == 1u);
    CHECK(m->maps.source.rfind("generated by the ps::engine_cycle map generator v1 (PHYS-033 P4 I7c C16a)", 0) == 0);
    CHECK(m->content_hash == pin.content_hash);
    CHECK(key == pin.cache_key);
}

